void drawText(uint8_t *bitmap, uint16_t widthBytes, uint16_t bitmapHeight, uint16_t x, uint16_t y,
              const char *text, uint8_t scale) {
    if (!bitmap || !text || scale == 0) return;
    uint16_t widthDots = (uint16_t)widthBytes * 8;
    uint16_t cx = x;

    for (const char *p = text; *p; p++) {
        char c = *p;
        if (c >= 'a' && c <= 'z') c = (char)(c - 'a' + 'A');  // this font is uppercase-only
        const uint8_t *glyph = glyphFor(c);

        if (glyph) {
            for (uint8_t row = 0; row < kGlyphHeight; row++) {
                uint8_t rowBits = glyph[row];
                if (rowBits == 0) continue;
                for (uint8_t col = 0; col < kGlyphWidth; col++) {
                    if (!(rowBits & (0x10 >> col))) continue;
                    for (uint8_t sy = 0; sy < scale; sy++) {
                        uint16_t yy = y + (uint16_t)row * scale + sy;
                        if (yy >= bitmapHeight) continue;
                        for (uint8_t sx = 0; sx < scale; sx++) {
                            uint16_t xx = cx + (uint16_t)col * scale + sx;
                            if (xx >= widthDots) continue;
                            bitmap[(size_t)yy * widthBytes + (xx >> 3)] |= (0x80 >> (xx & 7));
                        }
                    }
                }
            }
        }
        cx += (uint16_t)(kGlyphWidth + 1) * scale;  // 1-col (unscaled) gap between characters
    }
}

uint16_t textWidth(const char *text, uint8_t scale) {
    if (!text) return 0;
    size_t n = strlen(text);
    if (n == 0) return 0;
    return (uint16_t)(n * (kGlyphWidth + 1) - 1) * scale;  // no trailing gap after the last char
}

